function translateTextNode(node, lang) {
  if (!node.parentElement) return
  if (node.parentElement.closest('script, style, noscript, svg, textarea, [data-no-translate]')) return

  // Re-capture the original whenever the node changed outside this layer
  // (e.g. React re-rendered dynamic text); otherwise the first cached value
  // would be re-applied forever and dynamic text would freeze.
  if (!originalText.has(node) || (lastApplied.has(node) && lastApplied.get(node) !== node.nodeValue)) {
    originalText.set(node, node.nodeValue)
  }

  const original = originalText.get(node)
  const trimmed = original.trim()
  if (!trimmed) return

  const replacement = translations[lang]?.[trimmed] || trimmed
  const leading = original.match(/^\s*/)?.[0] || ''
  const trailing = original.match(/\s*$/)?.[0] || ''
  const nextValue = `${leading}${replacement}${trailing}`

  if (node.nodeValue !== nextValue) node.nodeValue = nextValue
  lastApplied.set(node, nextValue)
}

function applyTranslations(lang) {
  const root = document.getElementById('root')
  if (!root) return

  document.documentElement.lang = lang

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  const nodes = []
  while (walker.nextNode()) nodes.push(walker.currentNode)
  nodes.forEach((node) => translateTextNode(node, lang))
}

export default function TranslationLayer() {
  const location = useLocation()
  const lang = getLangFromPath(location.pathname)

  useEffect(() => {
    const root = document.getElementById('root')
    if (!root) return

    const observe = () => observer.observe(root, { childList: true, subtree: true, characterData: true })

    // Disconnect around our own DOM writes so the translation never re-triggers
    // itself. The old synchronous `applying` guard was already false by the
    // time the async observer callback fired, so each real mutation cost two
    // full-tree walks. MutationObserver already batches the records from one
    // React commit into a single callback, so this needs no extra debounce —
    // and staying synchronous (no requestAnimationFrame) keeps it working in
    // background/inactive tabs where rAF callbacks are throttled or withheld.
    const observer = new MutationObserver(() => {
      observer.disconnect()
      applyTranslations(lang)
      observe()
    })

    applyTranslations(lang)
    observe()

    return () => observer.disconnect()
  }, [lang, location.pathname, location.search])

  return null
}
