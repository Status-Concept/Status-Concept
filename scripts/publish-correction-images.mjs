import fs from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const privateRoot = path.resolve(process.argv[2] || path.join(root, '.catalog-private'))
const sourceRoot = path.join(privateRoot, 'final-images', 'correction-candidates')
const outputRoot = path.join(root, 'public', 'product-images', 'corrections')
const mapOutput = path.join(root, 'src', 'data', 'publishedCorrections.generated.js')
const categoryMap = { Lounge: 'lounge', Dining: 'dining', 'Accessories & Décor': 'decor' }

const [report, overrides, localProducts] = await Promise.all([
  fs.readFile(path.join(privateRoot, 'review', 'image-correction-results.json'), 'utf8').then(JSON.parse),
  fs.readFile(path.join(privateRoot, 'generated', 'image-correction-overrides.json'), 'utf8').then(JSON.parse),
  fs.readFile(path.join(privateRoot, 'generated', 'local-products.json'), 'utf8').then(JSON.parse),
])
if (report.entries?.length !== 139 || Object.keys(overrides).length !== 139) {
  throw new Error('Expected exactly 139 checklist entries and image mappings')
}

const localById = new Map(localProducts.map((product) => [product.id, product]))
const entriesByNumber = new Map(report.entries.map((entry) => [entry.number, entry]))
const publicImages = {}
const publicLocalProducts = []
await fs.mkdir(outputRoot, { recursive: true })

for (const [id, override] of Object.entries(overrides)) {
  const entry = entriesByNumber.get(override.checklistNumber)
  if (!entry || entry.name !== override.sourceName || entry.candidateSha256 !== override.sha256) {
    throw new Error(`Checklist mapping changed for ${id}`)
  }
  const source = path.resolve(privateRoot, entry.candidateImage)
  if (!source.startsWith(sourceRoot + path.sep) || entry.reviewStatus !== 'candidate-needs-human-visual-review') {
    throw new Error(`Invalid candidate for ${id}`)
  }
  const bytes = await fs.readFile(source)
  if (createHash('sha256').update(bytes).digest('hex') !== entry.candidateSha256) {
    throw new Error(`Image hash changed for ${id}`)
  }
  const filename = `${entry.number}-${id.replace(/[^a-z0-9-]/gi, '-').toLowerCase()}.webp`
  await sharp(bytes).rotate().resize({ width: 1600, height: 1600, fit: 'inside', withoutEnlargement: true })
    .flatten({ background: '#ffffff' }).webp({ quality: 84 }).toFile(path.join(outputRoot, filename))
  const image = `/product-images/corrections/${filename}`
  publicImages[id] = image

  const local = localById.get(id)
  if (local) {
    const category = categoryMap[local.category]
    if (!category || local.selectionStatus !== 'candidate') throw new Error(`Unpublishable local product ${id}`)
    publicLocalProducts.push({
      id,
      name: String(local.canonicalName).replace(/^[0-9]+[-._\s]+/, '').trim(),
      collection: local.collection,
      collectionName: local.collection,
      category,
      categoryLabel: local.category,
      img: image,
      images: [image],
      fit: 'contain',
      publishedCorrection: true,
    })
  }
}

if (Object.keys(publicImages).length !== 139 || publicLocalProducts.length !== 66) {
  throw new Error('Unexpected number of public images or local products')
}
const output = `// Generated by scripts/publish-correction-images.mjs. Public fields only.\n`
  + `export const publishedCorrectionImages = ${JSON.stringify(publicImages, null, 2)}\n`
  + `export const publishedLocalProducts = ${JSON.stringify(publicLocalProducts, null, 2)}\n`
await fs.writeFile(mapOutput, output, 'utf8')
console.log(JSON.stringify({ images: Object.keys(publicImages).length, localProducts: publicLocalProducts.length, outputRoot, mapOutput }))
