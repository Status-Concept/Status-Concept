import fs from 'node:fs'
import path from 'node:path'
import { createServer } from 'vite'

const repoRoot = process.cwd()
const outputPath = path.join(repoRoot, 'src', 'data', 'demoProducts.generated.js')

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' })
try {
  const { demoProducts } = await server.ssrLoadModule('/src/data/demoProducts.source.js')
  const imports = new Map()
  for (const product of demoProducts) {
    for (const image of [product.img, ...(product.images || [])]) {
      if (!image?.startsWith('/src/')) continue
      if (!imports.has(image)) imports.set(image, `image${imports.size}`)
    }
  }

  const serialize = (value) => {
    if (typeof value === 'string') return imports.get(value) || JSON.stringify(value)
    if (Array.isArray(value)) return `[${value.map(serialize).join(', ')}]`
    if (value && typeof value === 'object') {
      return `{ ${Object.entries(value).map(([key, item]) => `${JSON.stringify(key)}: ${serialize(item)}`).join(', ')} }`
    }
    return JSON.stringify(value)
  }

  const importLines = [...imports.entries()].map(([source, name]) => {
    const relative = source.replace(/^\/src\//, '../')
    return `import ${name} from ${JSON.stringify(relative)}`
  })
  const body = [
    '// Generated by scripts/generate-demo-products.mjs. Do not edit manually.',
    '// This file contains only the approved public demonstration selection.',
    ...importLines,
    '',
    `export const demoProducts = ${serialize(demoProducts)}`,
    '',
    'export const demoProductIds = new Set(demoProducts.map((product) => product.id).filter(Boolean))',
    '',
  ].join('\n')
  fs.writeFileSync(outputPath, body, 'utf8')
  console.log(`Generated ${demoProducts.length} public demo products at ${path.relative(repoRoot, outputPath)}`)
} finally {
  await server.close()
}
