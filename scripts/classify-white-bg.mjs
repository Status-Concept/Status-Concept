// Classifies every product's MAIN image as white-background or not, by sampling
// the border ring of pixels. Writes src/data/productImageStatus.js with the set
// of product ids that do NOT have a clean white-background image.
// Run: node scripts/classify-white-bg.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { catalogProducts } from "../src/data/catalogProducts.js";
import { glatzProducts } from "../src/data/glatzProducts.js";

const repoRoot = path.resolve(import.meta.dirname, "..");
const pub = path.join(repoRoot, "public");
const assets = path.join(repoRoot, "src", "assets", "images");

// --- resolve kitchen product id -> asset file (kitchenProducts.js uses imports) ---
const kitchenSrc = fs.readFileSync(path.join(repoRoot, "src", "data", "kitchenProducts.js"), "utf8");
const importMap = {};
for (const m of kitchenSrc.matchAll(/import\s+(kitchenImg\w+)\s+from\s+'([^']+)'/g)) {
  importMap[m[1]] = m[2].replace(/^\.\.\/assets\/images\//, "");
}
const kitchenItems = [];
for (const m of kitchenSrc.matchAll(/id:\s*'([^']+)',[\s\S]*?\n\s*img:\s*(kitchenImg\w+|"[^"]+")/g)) {
  const id = m[1];
  const imgRef = m[2];
  let file = null;
  if (imgRef.startsWith('"')) file = path.join(pub, imgRef.replace(/"/g, "")); // already a white-bg string path (none now)
  else if (importMap[imgRef]) file = path.join(assets, importMap[imgRef]);
  if (file) kitchenItems.push({ id, file });
}

// --- assemble every product shown on the site ---
const items = [
  { id: "sicily-modular-set", file: path.join(assets, "sicily-corner.jpg") },
  ...glatzProducts.map((p) => ({ id: p.id, file: path.join(pub, p.img) })),
  ...kitchenItems,
  ...catalogProducts.filter((p) => p.category !== "kitchen").map((p) => ({ id: p.id, file: path.join(pub, p.img) })),
];

const WHITE = 244;          // channel threshold for "near white"
const PASS_FRACTION = 0.85; // border must be this white to count as white-bg
const N = 64;               // downsample size
// Known studio images whose soft floor shadow lowers the border score even
// though the presentation is intentionally isolated on white.
const FORCE_WHITE = new Set(["sicily-modular-set"]);

async function borderWhiteFraction(file) {
  const { data, info } = await sharp(file).resize(N, N, { fit: "fill" }).flatten({ background: "#ffffff" }).raw().toBuffer({ resolveWithObject: true });
  const ch = info.channels;
  const w = info.width, h = info.height;
  let white = 0, total = 0;
  const isWhite = (x, y) => {
    const i = (y * w + x) * ch;
    return data[i] >= WHITE && data[i + 1] >= WHITE && data[i + 2] >= WHITE;
  };
  for (let x = 0; x < w; x++) { for (const y of [0, 1, h - 2, h - 1]) { total++; if (isWhite(x, y)) white++; } }
  for (let y = 0; y < h; y++) { for (const x of [0, 1, w - 2, w - 1]) { total++; if (isWhite(x, y)) white++; } }
  return white / total;
}

const results = [];
for (const it of items) {
  if (!fs.existsSync(it.file)) { results.push({ id: it.id, frac: -1, whiteBg: false, missing: true }); continue; }
  try {
    const frac = await borderWhiteFraction(it.file);
    results.push({ id: it.id, frac: +frac.toFixed(3), whiteBg: frac >= PASS_FRACTION });
  } catch (e) {
    results.push({ id: it.id, frac: -1, whiteBg: false, error: e.message });
  }
}

const noImage = results.filter((r) => !r.whiteBg && !FORCE_WHITE.has(r.id)).map((r) => r.id);
const whiteBg = results.filter((r) => r.whiteBg || FORCE_WHITE.has(r.id)).map((r) => r.id);

// Distribution to help calibrate
const buckets = {};
for (const r of results) { const b = r.frac < 0 ? "missing" : (Math.floor(r.frac * 10) / 10).toFixed(1); buckets[b] = (buckets[b] || 0) + 1; }

console.log(`Total products: ${results.length}`);
console.log(`WHITE-BG (keep image): ${whiteBg.length}`);
console.log(`NO clean white bg (placeholder): ${noImage.length}`);
console.log(`Border-white-fraction buckets:`, JSON.stringify(buckets));
console.log(`\nBorderline (0.70–0.92):`);
results.filter((r) => r.frac >= 0.70 && r.frac < 0.92).sort((a, b) => a.frac - b.frac).slice(0, 25).forEach((r) => console.log(`  ${r.frac}  ${r.id}`));

fs.writeFileSync(
  path.join(repoRoot, "src", "data", "productImageStatus.js"),
  `// Generated by scripts/classify-white-bg.mjs — product ids whose main image is NOT
// a clean white-background shot. These render a "No image" placeholder and sort last.
// Re-run the script after changing product images.
export const noImageProducts = new Set(${JSON.stringify(noImage.sort(), null, 2)});
`,
  "utf8",
);
console.log(`\nWrote src/data/productImageStatus.js (${noImage.length} ids)`);
