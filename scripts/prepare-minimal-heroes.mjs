// Convert built-in image-generation outputs and build contact sheets for review.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'
import { excludedRattanIds } from '../src/data/productExclusions.js'

const root = process.cwd()
const review = path.join(root, 'outputs', 'minimal-heroes')
const destination = path.join(root, 'public', 'product-images', 'hero-minimal')
await mkdir(review, { recursive: true })
await mkdir(destination, { recursive: true })
const jobs = JSON.parse(await readFile(path.join(review, 'jobs.json'), 'utf8'))
const [mode, id, source] = process.argv.slice(2)

if (mode === 'install') {
  if (!jobs.products.some((p) => p.id === id)) throw new Error('Unknown product ID')
  await sharp(source).resize({ width: 1600, withoutEnlargement: true }).webp({ quality: 90 }).toFile(path.join(destination, `${id}.webp`))
  console.log(`Saved ${id}`)
} else if (mode === 'sheets') {
  const products = jobs.products.filter((p) => (!id || p.id === id) && (source !== 'outputs' || existsSync(path.join(destination, `${p.id}.webp`))))
  for (let start = 0; start < products.length; start += 16) {
    const overlays = []
    const group = products.slice(start, start + 16)
    for (let i = 0; i < group.length; i++) {
      const p = group[i]
      const target = source === 'outputs' ? path.join(destination, `${p.id}.webp`) : p.source
      const thumbnail = await sharp(target).resize(240, 240, { fit: 'contain', background: '#ffffff' }).png().toBuffer()
      overlays.push({ input: thumbnail, left: (i % 4) * 240, top: Math.floor(i / 4) * 240 })
    }
    const file = path.join(review, `${source === 'outputs' ? 'results' : 'sources'}-${String(start / 16 + 1).padStart(2, '0')}.jpg`)
    await sharp({ create: { width: 960, height: Math.ceil(group.length / 4) * 240, channels: 3, background: '#ffffff' } }).composite(overlays).jpeg({ quality: 88 }).toFile(file)
    console.log(file)
  }
} else if (mode === 'manifest') {
  const files = new Set(await readdir(destination))
  const heroes = Object.fromEntries(jobs.products.filter((p) => !excludedRattanIds.has(p.id) && files.has(`${p.id}.webp`)).map((p) => [p.id, `/product-images/hero-minimal/${p.id}.webp`]))
  if (id !== 'partial' && Object.keys(heroes).length !== jobs.products.length) throw new Error('Not all minimal heroes have been generated')
  await writeFile(path.join(root, 'src', 'data', 'minimalProductHeroes.generated.js'), `// Generated by scripts/prepare-minimal-heroes.mjs.\nexport const minimalProductHeroes = ${JSON.stringify(heroes, null, 2)}\n`)
  console.log(`Mapped ${Object.keys(heroes).length} minimal heroes`)
} else throw new Error('Use install, sheets or manifest')
