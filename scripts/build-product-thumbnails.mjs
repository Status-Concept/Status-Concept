import sharp from 'sharp'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

export async function frameProductImage(file, part) {
  let input = sharp(file).flatten({ background: '#fff' })
  if (part) {
    const { width, height } = await input.metadata()
    const column = { left: 0, center: 1, right: 2 }[part]
    input = sharp(await input.extract({ left: Math.floor(width * column / 3), top: 0, width: Math.floor(width / 3), height }).toBuffer())
  }
  const flattened = await input.toBuffer()
  const cropped = await sharp(flattened).trim({ background: '#fff', threshold: 12 }).toBuffer()
  const { data, info } = await sharp(cropped).resize(1056, 1056, { fit: 'inside' }).png().toBuffer({ resolveWithObject: true })
  const buffer = await sharp({ create: { width: 1200, height: 1200, channels: 3, background: '#fff' } })
    .composite([{ input: data, left: Math.round((1200 - info.width) / 2), top: Math.round((1200 - info.height) / 2) }])
    .webp({ quality: 90 }).toBuffer()
  return { buffer, width: info.width, height: info.height }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { createServer } = await import('vite')
  const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' })
  try {
    const { publicSearchProducts } = await server.ssrLoadModule('/src/data/productCatalog.js')
    const { expandProductCollection, productHasImage } = await server.ssrLoadModule('/src/pages/status-concept-products.jsx')
    const products = expandProductCollection(expandProductCollection(publicSearchProducts, 'sicily'), 'bermuda').filter(productHasImage)
    const cutouts = new Set(['sicily-corner-module', 'sicily-centre-module', 'sicily-ottoman', 'bermuda-left-chair', 'bermuda-ottoman', 'bermuda-right-chair', 'glatz-sombrano-s-plus', 'glatz-alu-smart', 'glatz-alu-twist', 'glatz-castello-pro', 'glatz-palazzo-noblesse'])
    const target = 'public/product-images/cards-white-v1'
    await mkdir(target, { recursive: true })
    const thumbnails = {}, audit = []
    for (const product of products) {
      const source = cutouts.has(product.id) ? `src/assets/images/card-cutouts-v1/${product.id}.webp`
        : product.img.startsWith('/src/') ? product.img.slice(1) : `public${product.img}`
      const { buffer, width, height } = await frameProductImage(source, cutouts.has(product.id) ? null : product.imageCrop)
      const image = `/product-images/cards-white-v1/${product.id}.webp`
      await writeFile(`public${image}`, buffer)
      for (const size of [400, 800]) await sharp(buffer).resize(size).webp({ quality: 86 }).toFile(`public${image.slice(0, -5)}-w${size}.webp`)
      thumbnails[product.id] = image
      audit.push({ id: product.id, source, image, contentWidth: width, contentHeight: height, editedCutout: cutouts.has(product.id) })
    }
    thumbnails['sicily-modular-set'] = thumbnails['sicily-corner-module']
    thumbnails['bermuda-divano'] = '/product-images/cards-white-v1/bermuda-divano.webp'
    const bermuda = publicSearchProducts.find(p => p.id === 'bermuda-divano')
    const { buffer } = await frameProductImage(`public${bermuda.img}`)
    await writeFile(`public${thumbnails['bermuda-divano']}`, buffer)
    for (const size of [400, 800]) await sharp(buffer).resize(size).webp({ quality: 86 }).toFile(`public${thumbnails['bermuda-divano'].slice(0, -5)}-w${size}.webp`)
    await writeFile('src/data/productThumbnails.generated.js', `// Generated by scripts/build-product-thumbnails.mjs. Originals and collection covers stay unchanged.\nexport const productThumbnails = ${JSON.stringify(thumbnails, null, 2)}\n`)
    await writeFile('output/product-framing/audit.json', JSON.stringify(audit, null, 2))
    console.log(`Framed ${Object.keys(thumbnails).length} product thumbnails on white.`)
  } finally { await server.close() }
}
